import type { CanvasState, Field, FieldType } from "@/types/schema.types"
import type { GeneratorOptions } from "../compiler.types"

// Maps our internal field types to SQLAlchemy column types
const SQLALCHEMY_TYPE_MAP: Record<FieldType, string> = {
  UUID: "UUID(as_uuid=True)",
  VARCHAR: "String(255)",
  TEXT: "Text",
  INT: "Integer",
  BIGINT: "BigInteger",
  FLOAT: "Float",
  BOOLEAN: "Boolean",
  DATE: "Date",
  TIMESTAMP: "DateTime",
  JSON: "JSON",
}

// python-side imports needed per type, so we only import what's actually used
const TYPE_IMPORTS: Partial<Record<FieldType, string>> = {
  UUID: "from sqlalchemy.dialects.postgresql import UUID",
}

function toSnakeCase(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/\s+/g, "_")
    .toLowerCase()
}

function toPascalCase(name: string): string {
  return name
    .split(/[\s_-]+/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("")
}

function generateFieldLine(
  field: Field,
  isForeignKey: boolean,
  fkTarget?: string
): string {
  const columnArgs: string[] = [SQLALCHEMY_TYPE_MAP[field.type]]

  if (isForeignKey && fkTarget) {
    columnArgs.push(`ForeignKey("${fkTarget}")`)
  }
  if (field.isPrimaryKey) columnArgs.push("primary_key=True")
  if (field.isUnique && !field.isPrimaryKey) columnArgs.push("unique=True")
  if (!field.isNullable) columnArgs.push("nullable=False")

  return `    ${toSnakeCase(field.name)} = Column(${columnArgs.join(", ")})`
}

export function generateSQLAlchemy(
  canvasState: CanvasState,
  options?: GeneratorOptions
): string {
  const usedTypes = new Set(
    canvasState.tables.flatMap((t) => t.fields.map((f) => f.type))
  )
  const extraImports = [...usedTypes]
    .map((t) => TYPE_IMPORTS[t])
    .filter((imp): imp is string => imp !== undefined)

  const header = [
    "# Generated by RodSchema",
    options?.author ? `# Author: ${options.author}` : null,
    "",
    "from sqlalchemy import Column, ForeignKey",
    ...extraImports,
    "from sqlalchemy.orm import declarative_base, relationship",
    "",
    "Base = declarative_base()",
    "",
  ]
    .filter((line): line is string => line !== null)
    .join("\n")

  const modelBlocks = canvasState.tables.map((table) => {
    const className = toPascalCase(table.name)

    const fieldLines = table.fields.map((field) => {
      const relation = canvasState.relations.find(
        (r) => r.from.tableId === table.id && r.from.fieldId === field.id
      )

      if (relation) {
        const parentTable = canvasState.tables.find(
          (t) => t.id === relation.to.tableId
        )
        const parentField = parentTable?.fields.find(
          (f) => f.id === relation.to.fieldId
        )
        if (parentTable && parentField) {
          return generateFieldLine(
            field,
            true,
            `${toSnakeCase(parentTable.name)}.${toSnakeCase(parentField.name)}`
          )
        }
      }

      return generateFieldLine(field, false)
    })

    // relationship() declarations — the ORM-level convenience accessors,
    // separate from the raw Column/ForeignKey definitions above
    const relationshipLines: string[] = []
    for (const relation of canvasState.relations) {
      const isChildSide = relation.from.tableId === table.id
      const isParentSide = relation.to.tableId === table.id
      if (!isChildSide && !isParentSide) continue

      if (isChildSide) {
        const parentTable = canvasState.tables.find(
          (t) => t.id === relation.to.tableId
        )
        if (!parentTable) continue
        relationshipLines.push(
          `    ${toSnakeCase(parentTable.name)} = relationship("${toPascalCase(parentTable.name)}", back_populates="${toSnakeCase(table.name)}s")`
        )
      } else {
        const childTable = canvasState.tables.find(
          (t) => t.id === relation.from.tableId
        )
        if (!childTable) continue
        relationshipLines.push(
          `    ${toSnakeCase(childTable.name)}s = relationship("${toPascalCase(childTable.name)}", back_populates="${toSnakeCase(table.name)}")`
        )
      }
    }

    return [
      `class ${className}(Base):`,
      `    __tablename__ = "${toSnakeCase(table.name)}"`,
      "",
      ...fieldLines,
      ...(relationshipLines.length ? ["", ...relationshipLines] : []),
    ].join("\n")
  })

  return [header, modelBlocks.join("\n\n\n")].join("\n")
}
