import type { CanvasState, Field, FieldType } from "@/types/schema.types"
import type { GeneratorOptions } from "../compiler.types"

// Maps our internal field types to standard SQL column types.
// Kept as its own lookup so extending FieldTypeEnum later only means
// adding one line here, not touching the generator logic itself.
const SQL_TYPE_MAP: Record<FieldType, string> = {
  UUID: "UUID",
  VARCHAR: "VARCHAR(255)",
  TEXT: "TEXT",
  INT: "INTEGER",
  BIGINT: "BIGINT",
  FLOAT: "DOUBLE PRECISION",
  BOOLEAN: "BOOLEAN",
  DATE: "DATE",
  TIMESTAMP: "TIMESTAMP",
  JSON: "JSONB",
}

function generateFieldLine(field: Field): string {
  const parts = [`  "${field.name}" ${SQL_TYPE_MAP[field.type]}`]

  if (field.isPrimaryKey) parts.push("PRIMARY KEY")
  if (!field.isNullable) parts.push("NOT NULL")
  if (field.isUnique && !field.isPrimaryKey) parts.push("UNIQUE") // PK is already implicitly unique

  return parts.join(" ")
}

export function generateSQL(
  canvasState: CanvasState,
  options?: GeneratorOptions
): string {
  const header = [
    "-- Generated by RodSchema",
    options?.author ? `-- Author: ${options.author}` : null,
    "",
  ]
    .filter((line): line is string => line !== null)
    .join("\n")

  const tableStatements = canvasState.tables.map((table) => {
    const fieldLines = table.fields.map(generateFieldLine)

    // Foreign key constraints for this table are added as separate ALTER
    // statements after all CREATE TABLEs, so table creation order never matters
    return `CREATE TABLE "${table.name}" (\n${fieldLines.join(",\n")}\n);`
  })

  const fkStatements = canvasState.relations
    .map((relation) => {
      const fromTable = canvasState.tables.find(
        (t) => t.id === relation.from.tableId
      )
      const toTable = canvasState.tables.find(
        (t) => t.id === relation.to.tableId
      )
      const fromField = fromTable?.fields.find(
        (f) => f.id === relation.from.fieldId
      )
      const toField = toTable?.fields.find((f) => f.id === relation.to.fieldId)

      if (!fromTable || !toTable || !fromField || !toField) return null

      // The "from" side is treated as the referencing (FK) side by convention —
      // i.e. from = child table with the foreign key, to = parent table being referenced
      return [
        `ALTER TABLE "${fromTable.name}"`,
        `  ADD CONSTRAINT "fk_${fromTable.name}_${fromField.name}"`,
        `  FOREIGN KEY ("${fromField.name}") REFERENCES "${toTable.name}"("${toField.name}")`,
        `  ON DELETE CASCADE;`,
      ].join("\n")
    })
    .filter((stmt): stmt is string => stmt !== null)

  return [header, ...tableStatements, "", ...fkStatements].join("\n\n")
}
