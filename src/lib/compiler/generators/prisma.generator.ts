import type {
  CanvasState,
  Field,
  FieldType,
  RelationType,
} from "@/types/schema.types"
import type { GeneratorOptions } from "../compiler.types"

// Maps our internal field types to Prisma's scalar types
const PRISMA_TYPE_MAP: Record<FieldType, string> = {
  UUID: "String", // Prisma has no native UUID scalar — represented as String with @db.Uuid
  VARCHAR: "String",
  TEXT: "String",
  INT: "Int",
  BIGINT: "BigInt",
  FLOAT: "Float",
  BOOLEAN: "Boolean",
  DATE: "DateTime",
  TIMESTAMP: "DateTime",
  JSON: "Json",
}

// Native DB type attributes Prisma needs for types that don't map 1:1 to its scalars
const NATIVE_TYPE_ATTR: Partial<Record<FieldType, string>> = {
  UUID: "@db.Uuid",
  DATE: "@db.Date",
}

function generateFieldLine(field: Field): string {
  const parts = [field.name, PRISMA_TYPE_MAP[field.type]]

  if (field.isNullable) parts[1] += "?"

  const attributes: string[] = []
  if (field.isPrimaryKey) attributes.push("@id")
  if (field.isUnique && !field.isPrimaryKey) attributes.push("@unique")
  if (field.type === "UUID" && field.isPrimaryKey)
    attributes.push("@default(uuid())")
  const nativeAttr = NATIVE_TYPE_ATTR[field.type]
  if (nativeAttr) attributes.push(nativeAttr)

  return [...parts, ...attributes].join(" ")
}

function relationFieldName(
  targetTableName: string,
  type: RelationType
): string {
  // one-to-many / many-to-many on the "many" side get a plural relation field name
  if (type === "one-to-many" || type === "many-to-many") {
    return `${targetTableName.toLowerCase()}s`
  }
  return targetTableName.toLowerCase()
}

export function generatePrismaSchema(
  canvasState: CanvasState,
  options?: GeneratorOptions
): string {
  const header = [
    "// Generated by RodSchema",
    options?.author ? `// Author: ${options.author}` : null,
    "",
    "generator client {",
    '  provider = "prisma-client"',
    '  output   = "./generated"',
    "}",
    "",
    "datasource db {",
    '  provider = "postgresql"',
    "}",
    "",
  ]
    .filter((line): line is string => line !== null)
    .join("\n")

  const modelBlocks = canvasState.tables.map((table) => {
    const fieldLines = table.fields.map((f) => `  ${generateFieldLine(f)}`)

    // Relation fields: for every relation touching this table, add the Prisma
    // relation field + the matching scalar/foreign key line on the child side
    const relationLines: string[] = []

    for (const relation of canvasState.relations) {
      const isChildSide = relation.from.tableId === table.id
      const isParentSide = relation.to.tableId === table.id
      if (!isChildSide && !isParentSide) continue

      if (isChildSide) {
        const parentTable = canvasState.tables.find(
          (t) => t.id === relation.to.tableId
        )
        const fkField = table.fields.find((f) => f.id === relation.from.fieldId)
        if (!parentTable || !fkField) continue

        const relName = relationFieldName(parentTable.name, "one-to-one") // singular on child side
        relationLines.push(
          `  ${relName} ${parentTable.name} @relation(fields: [${fkField.name}], references: [${
            parentTable.fields.find((f) => f.id === relation.to.fieldId)
              ?.name ?? "id"
          }])`
        )
      } else {
        const childTable = canvasState.tables.find(
          (t) => t.id === relation.from.tableId
        )
        if (!childTable) continue

        const relName = relationFieldName(childTable.name, relation.type)
        const isList =
          relation.type === "one-to-many" || relation.type === "many-to-many"
        relationLines.push(
          `  ${relName} ${childTable.name}${isList ? "[]" : "?"}`
        )
      }
    }

    return `model ${table.name} {\n${[...fieldLines, ...relationLines].join("\n")}\n}`
  })

  return [header, modelBlocks.join("\n\n")].join("\n")
}
